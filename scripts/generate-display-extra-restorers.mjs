// Build-time, finite extra display layouts. No runtime generation from packets.
import fs from 'node:fs';
import assert from 'node:assert/strict';
const shapes=JSON.parse(fs.readFileSync('scripts/lib/display-restore-extra-shapes.json','utf8'));
const stable=new Set(JSON.parse(fs.readFileSync('scripts/lib/display-restore-shapes.json','utf8')).map(keys=>JSON.stringify(keys)));
assert.ok(shapes.length>0&&shapes.length<=16);
const seen=new Set();
for(const keys of shapes){
 assert.ok(Array.isArray(keys)&&keys.length>=6&&keys.length<=128);
 const signature=JSON.stringify(keys);assert.ok(!stable.has(signature)&&!seen.has(signature));seen.add(signature);
 assert.equal(new Set(keys).size,keys.length);
 for(const key of keys)assert.ok(/^[A-Za-z_][A-Za-z0-9_]*$/.test(key)&&!['__proto__','constructor','prototype'].includes(key));
}
let code=`// Generated by scripts/generate-display-extra-restorers.mjs. Do not hand edit.
// Exact static layouts only; every field keeps depth/guard/read/write ordering.
// Disabled by default. Never compile incoming metadata as executable code.
import type { DisplayRecordRestore } from './DisplayRecordRestore.generated';
const definitions:Array<{keys:readonly string[];restore:DisplayRecordRestore}> = import.meta.env.VITE_LAN_EXTRA_DISPLAY_LAYOUTS === 'true' ? [
`;
for(const keys of shapes){
 code+=` {keys:${JSON.stringify(keys)},restore(values,output,ships,layouts,depth,decode,guard){\n  let value,previous;\n`;
 for(const [i,key] of keys.entries())code+=`  value=values[${i}]; if(depth>64)throw Error('Snapshot nesting exceeds limit'); guard(output,${JSON.stringify(key)}); previous=output.${key};\n  output.${key}=value===null||typeof value!=='object'?value:decode(value,previous,ships,layouts,depth);\n`;
 code+=' }},\n';
}
code+=`] : [];
const buckets=new Map<string,Map<number,typeof definitions>>();
for(const definition of definitions){
 const keys=definition.keys;let byLength=buckets.get(keys[0]);if(!byLength)buckets.set(keys[0],byLength=new Map());
 let bucket=byLength.get(keys.length);if(!bucket)byLength.set(keys.length,bucket=[]);bucket.push(definition);
}
export function extraDisplayRecordRestorer(keys:readonly string[]):DisplayRecordRestore|undefined {
 for(const definition of buckets.get(keys[0])?.get(keys.length)??[])if(definition.keys.every((key,i)=>keys[i]===key))return definition.restore;
}
`;
const output='src/network/DisplayRecordRestoreExtra.generated.ts';
if(process.argv.includes('--check'))assert.equal(fs.readFileSync(output,'utf8'),code,'Regenerate extra display layouts');
else fs.writeFileSync(output,code);
