// Build-time only. No runtime code generation or network-controlled source text.
import fs from 'node:fs';
import assert from 'node:assert/strict';
const shapes=JSON.parse(fs.readFileSync('scripts/lib/native-restore-shapes.json','utf8'));
const forbidden=new Set(['__proto__','prototype','constructor']);
assert.ok(shapes.length<=128);
for(const keys of shapes){assert.ok(keys.length>0&&keys.length<=2048);assert.equal(new Set(keys).size,keys.length);for(const key of keys)assert.ok(/^[A-Za-z_][A-Za-z0-9_]*$/.test(key)&&!forbidden.has(key));}
const vectors=new Set(['pos','vel','relativePos','localPos','offset','velocity','aimTargetWorld','teleportCameraOffset','startPos','endPos','barrelOffset','rayEndPrevFrame','localOffset']);
let code=`/* eslint-disable @typescript-eslint/no-explicit-any */
// Generated by scripts/generate-native-record-restorers.mjs. Do not hand edit.
// Finite known layouts only; exact field/order matching, unknown shapes fall back.
// Does not authorize a layout or bypass any wire validation.
import { Vector2 } from '../engine/math/Vector2';
type Decode = (value: any, previous: any, depth: number) => any;
export type NativeRecordRestore = ((values: any, output: any, depth: number, decode: Decode) => void) & {
  rows?: (values: any[], output: any[], depth: number, decode: Decode) => void;
  columns?: (row: any[], fixed: any[], dynamic: number[], output: any, depth: number, decode: Decode) => void;
};
/** Small hot-vector path. Preserve generic tag precedence, validation and
 * viewer identity even if a normally-vector field contains a different tag. */
function vector(value: any, previous: any, depth: number, decode: Decode): any {
  if (value.$vector && !value.$undefined && !value.$ship
      && !Object.hasOwn(value, '$component') && !Object.hasOwn(value, '$record')) {
    const xy = value.$vector;
    if (!Array.isArray(xy) || xy.length !== 2 || !xy.every(Number.isFinite)) throw Error('Invalid vector');
    return previous instanceof Vector2 ? previous.set(xy[0], xy[1]) : new Vector2(xy[0], xy[1]);
  }
  return decode(value, previous, depth);
}
const definitions: Array<{ keys: readonly string[]; restore: NativeRecordRestore; rows?: NativeRecordRestore['rows']; columns?: NativeRecordRestore['columns'] }> = [\n`;
function fields(keys, indent, columns=false) {
 let out=indent+(columns?'let value, index;\n':'let value;\n');
 keys.forEach((key,i)=>{
  out+=indent+(columns?`index = dynamic[${i}]; value = index ? row[index] : fixed[${i}];\n`:`value = values[${i}];\n`);
  if(!i)out+=indent+'if (depth > 64) throw Error("Snapshot nesting exceeds limit");\n';
  out+=indent+`output.${key} = value === null || typeof value !== 'object' ? value : ${vectors.has(key)?'vector':'decode'}(value, output.${key}, depth${vectors.has(key)?', decode':''});\n`;
 });return out;
}
for(const keys of shapes){
 code+=`  { keys: ${JSON.stringify(keys)}, restore(values, output, depth, decode) {\n${fields(keys,'    ')}  }`;
 // Armor requires owned cell restoration. Large ship/system layouts do not
 // benefit from a duplicated list loop; keep code size/JIT work bounded.
 if(keys.length<=32&&!keys.includes('cells'))code+=`, rows(rows, target, depth, decode) {
    for (let row = 0; row < rows.length; row++) {
      const values = rows[row];
      if (!Array.isArray(values) || values.length !== ${keys.length}) throw Error('Invalid snapshot record row');
      const previous = target[row];
      const output = previous && typeof previous === 'object' && !Array.isArray(previous) ? previous : {};
${fields(keys,'      ')}      target[row] = output;
    }
    target.length = rows.length;
  }`;
 if(keys.includes('ballisticTail'))code+=`, columns(row, fixed, dynamic, output, depth, decode) {\n${fields(keys,'    ',true)}  }`;
 code+=' },\n';
}
code+=`];
const byFirst = new Map<string, Map<number, typeof definitions>>();
for (const definition of definitions) {
  definition.restore.rows = definition.rows;
  definition.restore.columns = definition.columns;
  const keys = definition.keys;
  let byLength = byFirst.get(keys[0]);
  if (!byLength) byFirst.set(keys[0], byLength = new Map());
  let bucket = byLength.get(keys.length);
  if (!bucket) byLength.set(keys.length, bucket = []);
  bucket.push(definition);
}
export function nativeRecordRestorer(keys: readonly string[]): NativeRecordRestore | undefined {
  for (const definition of byFirst.get(keys[0])?.get(keys.length) ?? []) {
    if (definition.keys.every((key, index) => key === keys[index])) return definition.restore;
  }
}
`;
const file='src/network/NativeRecordRestore.generated.ts';
if(process.argv.includes('--check'))assert.equal(fs.readFileSync(file,'utf8'),code,'Regenerate native record restorers');else fs.writeFileSync(file,code);
