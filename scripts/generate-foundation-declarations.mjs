/** Generate checked declarations from their JSDoc implementation, never maintain both by hand. */
import fs from 'node:fs';
import path from 'node:path';
import ts from 'typescript';
const root = path.resolve(import.meta.dirname, '..');
const files = ['src/shared/VersionedMigration.mjs'].map(file => path.join(root, file));
const program = ts.createProgram(files, {
  target: ts.ScriptTarget.ES2023, module: ts.ModuleKind.NodeNext, moduleResolution: ts.ModuleResolutionKind.NodeNext,
  strict: true, allowJs: true, checkJs: true, declaration: true, emitDeclarationOnly: true, skipLibCheck: false,
});
const diagnostics = ts.getPreEmitDiagnostics(program);
if (diagnostics.length) {
  console.error(ts.formatDiagnosticsWithColorAndContext(diagnostics, {
    getCanonicalFileName: file => file, getCurrentDirectory: () => root, getNewLine: () => '\n',
  }));
  process.exitCode = 1;
} else {
  const check = process.argv.includes('--check');
  const result = program.emit(undefined, (file, content) => {
    const generated = '// Generated by scripts/generate-foundation-declarations.mjs; do not edit.\n' + content;
    if (check) {
      if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== generated) {
        console.error('Stale generated declaration: ' + path.relative(root, file)); process.exitCode = 1;
      }
    } else fs.writeFileSync(file, generated);
  });
  if (result.emitSkipped) process.exitCode = 1;
  if (!process.exitCode) console.log(check ? 'Foundation declarations are current.' : 'Foundation declarations generated.');
}
