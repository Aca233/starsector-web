// Build-time only. Finite layouts sampled from production LAN display packets.
// No eval/Function or network-provided source code; unknown layouts stay generic.
import fs from 'node:fs';
import assert from 'node:assert/strict';
const shapes=JSON.parse(fs.readFileSync('scripts/lib/display-restore-shapes.json','utf8'));
assert.ok(shapes.length<=64);
for(const keys of shapes){assert.ok(keys.length>0&&keys.length<=128);assert.equal(new Set(keys).size,keys.length);for(const key of keys)assert.ok(/^[A-Za-z_][A-Za-z0-9_]*$/.test(key)&&!['__proto__','prototype','constructor'].includes(key));}
let code=`// Generated by scripts/generate-display-record-restorers.mjs. Do not hand edit.
// Exact layout matching is only an optimization, never authorization: EVERY
// field retains its depth check, guard, eager previous read and ordered write.
type Decode = (value:any, previous:any, ships:Map<string,object>, layouts:any, depth:number)=>any;
type Guard = (target:object,key:string)=>void;
export type DisplayRecordRestore = (values:any[], output:any, ships:Map<string,object>, layouts:any, depth:number, decode:Decode, guard:Guard)=>void;
const definitions:Array<{keys:readonly string[];restore:DisplayRecordRestore}>=[
`;
for(const keys of shapes){
 code+=` {keys:${JSON.stringify(keys)},restore(values,output,ships,layouts,depth,decode,guard){\n  let value,previous;\n`;
 for(const [i,key] of keys.entries())code+=`  value=values[${i}]; if(depth>64)throw Error('Snapshot nesting exceeds limit'); guard(output,${JSON.stringify(key)}); previous=output.${key};\n  output.${key}=value===null||typeof value!=='object'?value:decode(value,previous,ships,layouts,depth);\n`;
 code+=' }},\n';
}
code+=`];
const buckets=new Map<string,Map<number,typeof definitions>>();
for(const definition of definitions){
 const keys=definition.keys;let byLength=buckets.get(keys[0]);if(!byLength)buckets.set(keys[0],byLength=new Map());
 let bucket=byLength.get(keys.length);if(!bucket)byLength.set(keys.length,bucket=[]);bucket.push(definition);
}
export function displayRecordRestorer(keys:readonly string[]):DisplayRecordRestore|undefined {
 for(const definition of buckets.get(keys[0])?.get(keys.length)??[])if(definition.keys.every((key,i)=>keys[i]===key))return definition.restore;
}
`;
const file='src/network/DisplayRecordRestore.generated.ts';
if(process.argv.includes('--check'))assert.equal(fs.readFileSync(file,'utf8'),code,'Regenerate display record restorers');else fs.writeFileSync(file,code);
